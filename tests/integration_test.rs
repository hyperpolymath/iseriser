// ---------------------------------------------------------------------------
// Test 8: Manifest init and reload round-trip
// ---------------------------------------------------------------------------

#[test]
fn test_manifest_init_round_trip() {
    let tmp = tempdir().unwrap();
    let dir = tmp.path().to_str().unwrap();

    // Init creates a file
    iseriser::manifest::init_manifest(dir).expect("init failed");

    let manifest_path = tmp.path().join("iseriser.toml");
    assert!(
        manifest_path.exists(),
        "iseriser.toml should exist after init"
    );

    // The generated file should be parseable
    let content = std::fs::read_to_string(&manifest_path).unwrap();
    let m = parse_manifest(&content).expect("generated manifest should parse");
    validate(&m).expect("generated manifest should validate");
}

