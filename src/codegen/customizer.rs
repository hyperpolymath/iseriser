// Template customizer.
//
// After the scaffold engine generates the base file set, the customizer
// applies language-specific modifications:
//
//   - Paradigm-specific Cargo features / dependencies
//   - Type-system-depth-dependent ABI proof richness
//   - Compilation-target-specific FFI bridge shape
//   - Extra files for specific targets (NIF boilerplate for BEAM, etc.)

use std::path::PathBuf;

use crate::abi::{CompilationTarget, GeneratedFile, LanguageModel, Paradigm};

// ---------------------------------------------------------------------------
// Public API
// ---------------------------------------------------------------------------

/// Apply all language-specific customizations to the generated file set.
///
/// This mutates `files` in place: it may append new files and modify
/// existing file contents.
pub fn apply_customizations(model: &LanguageModel, files: &mut Vec<GeneratedFile>) {
    // 1. Add paradigm-specific extras
    apply_paradigm_extras(model, files);

    // 2. Add target-specific extras
    apply_target_extras(model, files);

    // 3. Add type-system-specific extras
    apply_type_system_extras(model, files);
}

// ---------------------------------------------------------------------------
// Paradigm customizations
// ---------------------------------------------------------------------------

/// Add paradigm-specific files and modifications.
fn apply_paradigm_extras(model: &LanguageModel, files: &mut Vec<GeneratedFile>) {
    match model.paradigm {
        Paradigm::Functional => {
            // Functional languages often benefit from ADT mapping utilities
            files.push(generate_adt_mapper(model));
        }
        Paradigm::Array => {
            // Array languages need bulk data transfer helpers
            files.push(generate_array_bridge(model));
        }
        Paradigm::Dataflow => {
            // Dataflow languages need streaming/channel utilities
            files.push(generate_dataflow_bridge(model));
        }
        Paradigm::Logic => {
            // Logic languages need unification/backtracking FFI
            files.push(generate_logic_bridge(model));
        }
        Paradigm::Imperative => {
            // Imperative is the baseline — no extra files needed
        }
    }
}

/// Generate an ADT (algebraic data type) mapping utility for functional languages.
fn generate_adt_mapper(model: &LanguageModel) -> GeneratedFile {
    let iser_name = model.iser_name();
    let content = format!(
        r#"// SPDX-License-Identifier: MPL-2.0
// Copyright (c) 2026 Jonathan D.A. Jewell <j.d.a.jewell@open.ac.uk>
//
// ADT mapping utilities for {iser_name}.
// Maps Rust enums/structs to {lang_name} algebraic data types.
// Generated by iseriser (functional paradigm customization).

/// Trait for types that can be mapped to {lang_name} ADTs.
pub trait ToAdt {{
    /// The {lang_name}-side type name.
    fn adt_name(&self) -> &str;
    /// Serialise to the {lang_name} wire format.
    fn to_wire(&self) -> Vec<u8>;
}}
"#,
        iser_name = iser_name,
        lang_name = model.name,
    );
    GeneratedFile {
        path: PathBuf::from("src/codegen/adt_mapper.rs"),
        content,
    }
}

