    // Dependent types should generate deep ABI proof docs
    assert!(
        repo.files
            .iter()
            .any(|f| f.path.to_str().unwrap().contains("deep-abi-proofs")),
        "dependent type language should have deep ABI proof docs"
    );

    // Verify the Idris2 Types.idr mentions deep proofs
