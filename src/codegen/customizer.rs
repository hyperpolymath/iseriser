// ---------------------------------------------------------------------------
// Compilation target customizations
// ---------------------------------------------------------------------------

/// Add compilation-target-specific files.
fn apply_target_extras(model: &LanguageModel, files: &mut Vec<GeneratedFile>) {
    match model.compilation_target {
        CompilationTarget::Beam => {
            files.push(generate_beam_nif_boilerplate(model));
        }
        CompilationTarget::Jvm => {
            files.push(generate_jni_boilerplate(model));
        }
        CompilationTarget::Wasm => {
            files.push(generate_wasm_bindings(model));
        }
        CompilationTarget::Js => {
            files.push(generate_js_bridge(model));
        }
        CompilationTarget::Native | CompilationTarget::Interpreted | CompilationTarget::Gpu => {
            // Handled by the base scaffold
        }
    }
}

