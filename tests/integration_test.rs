use tempfile::tempdir;

// ---------------------------------------------------------------------------
// Helper: build a manifest TOML string from parameters
// ---------------------------------------------------------------------------

fn make_toml(
    lang_name: &str,
    paradigm: &str,
    type_sys: &str,
    target: &str,
    primitives: &[&str],
) -> String {
    let iser_name = format!("{}iser", lang_name.to_lowercase());
    let prims: Vec<String> = primitives.iter().map(|p| format!("\"{}\"", p)).collect();
    format!(
        r#"
[project]
name = "{iser_name}"
version = "0.1.0"

[language]
name = "{lang_name}"
paradigm = "{paradigm}"
type-system = "{type_sys}"
compilation-target = "{target}"
key-primitives = [{primitives}]

[output]
repo-name = "{iser_name}"
github-org = "hyperpolymath"
description = "{lang_name} interop -iser — generated by iseriser"
"#,
        iser_name = iser_name,
        lang_name = lang_name,
        paradigm = paradigm,
        type_sys = type_sys,
        target = target,
        primitives = prims.join(", "),
    )
}

// ---------------------------------------------------------------------------
// Test 1: Full pipeline for an imperative/native language (Chapel)
// ---------------------------------------------------------------------------

#[test]
fn test_full_pipeline_chapel() {
    let toml = make_toml(
        "Chapel",
        "imperative",
        "simple",
        "native",
        &["task", "locale", "domain", "forall", "sync"],
    );
    let manifest = parse_manifest(&toml).expect("parse failed");
    validate(&manifest).expect("structural validation failed");

    let report = validate_language_description(&manifest);
    assert!(
        report.is_valid(),
        "semantic validation failed: {:?}",
        report.errors
    );

    let tmp = tempdir().unwrap();
    let result = scaffold_repo(&manifest, tmp.path());
    assert!(
        result.is_success(),
        "scaffold failed: {:?}",
        result.error_message()
    );

    let repo = result.repo().unwrap();
    assert_eq!(repo.name, "chapeliser");
    assert!(
        repo.is_complete(),
        "generated repo missing mandatory categories"
    );
    assert!(
        repo.file_count() >= 20,
        "expected 20+ files, got {}",
        repo.file_count()
    );

    // Verify key files exist on disk
    let root = tmp.path().join("chapeliser");
    assert!(root.join("Cargo.toml").exists(), "Cargo.toml missing");
    assert!(root.join("src/main.rs").exists(), "src/main.rs missing");
    assert!(
        root.join("src/interface/abi/Types.idr").exists(),
        "Types.idr missing"
    );
    assert!(
        root.join("ffi/zig/src/main.zig").exists(),
        "main.zig missing"
    );
    assert!(root.join("README.adoc").exists(), "README.adoc missing");
    assert!(root.join("TOPOLOGY.md").exists(), "TOPOLOGY.md missing");

    // Verify Cargo.toml content
    let cargo = std::fs::read_to_string(root.join("Cargo.toml")).unwrap();
    assert!(cargo.contains("chapeliser"), "Cargo.toml missing repo name");
    assert!(
        cargo.contains("PMPL-1.0-or-later"),
        "Cargo.toml missing license"
    );
}

// ---------------------------------------------------------------------------
// Test 2: Functional / BEAM language (Gleam)
// ---------------------------------------------------------------------------

#[test]
fn test_full_pipeline_gleam_functional_beam() {
    let toml = make_toml(
        "Gleam",
        "functional",
        "algebraic",
        "beam",
        &["result", "option", "dynamic"],
    );
    let manifest = parse_manifest(&toml).unwrap();
    validate(&manifest).unwrap();

    let tmp = tempdir().unwrap();
    let result = scaffold_repo(&manifest, tmp.path());
    assert!(result.is_success());

    let repo = result.repo().unwrap();
    assert_eq!(repo.name, "gleamiser");
    assert!(repo.is_complete());

    // Functional paradigm should generate ADT mapper
    assert!(
        repo.files
            .iter()
            .any(|f| f.path.to_str().unwrap().contains("adt_mapper")),
        "functional language should have adt_mapper"
    );

    // BEAM target should generate NIF boilerplate
    assert!(
        repo.files
            .iter()
            .any(|f| f.path.to_str().unwrap().contains("beam_nif")),
        "BEAM target should have beam_nif"
    );
}

