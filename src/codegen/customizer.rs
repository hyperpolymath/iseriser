// ---------------------------------------------------------------------------
// Type system customizations
// ---------------------------------------------------------------------------

/// Add type-system-specific files when the language has rich types.
fn apply_type_system_extras(model: &LanguageModel, files: &mut Vec<GeneratedFile>) {
    if model.needs_deep_abi_proofs() {
        files.push(generate_deep_proof_readme(model));
    }
}

/// Generate a README explaining the deep ABI proof strategy.
fn generate_deep_proof_readme(model: &LanguageModel) -> GeneratedFile {
    let iser_name = model.iser_name();
    let content = format!(
        r#"= {iser_name} Deep ABI Proofs

{lang_name} has a rich type system ({type_sys}), so this -iser generates
enhanced Idris2 ABI proofs that verify:

* Type correspondence between Rust and {lang_name} representations
* Ownership/linearity preservation across the FFI boundary
* Refinement contract propagation

See `src/interface/abi/Types.idr` for the formal definitions.
"#,
        iser_name = iser_name,
        lang_name = model.name,
        type_sys = model.type_system,
    );
    GeneratedFile {
        path: PathBuf::from("docs/deep-abi-proofs.adoc"),
        content,
    }
}

// ---------------------------------------------------------------------------
// Unit tests
